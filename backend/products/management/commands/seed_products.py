class Command(BaseCommand):
    help = "Seed all 44 flower products and categories for Floral Delight"

    def handle(self, *args, **options):
        from django.db import connection

        self.stdout.write("Fixing PostgreSQL sequence if needed...")
        with connection.cursor() as cursor:
            cursor.execute("SELECT COALESCE(MAX(id), 0) FROM products_product;")
            max_id = cursor.fetchone()[0]
            if max_id > 0:
                cursor.execute(
                    "SELECT setval(pg_get_serial_sequence('products_product', 'id'), %s, false);",
                    [max_id + 1]
                )

        self.stdout.write("Seeding botanical categories...")
        category_objs = {}
        for cat in CATEGORIES_DATA:
            obj, _ = Category.objects.get_or_create(
                slug=cat["slug"],
                defaults={"name": cat["name"], "description": cat["description"]}
            )
            category_objs[cat["slug"]] = obj

        self.stdout.write(f"Seeding {len(PRODUCTS_DATA)} flower products...")
        count = 0
        for p in PRODUCTS_DATA:
            cat_slug = p["category_slug"]
            if cat_slug not in category_objs:
                cat_slug = "mixed"
            category = category_objs[cat_slug]

            Product.objects.update_or_create(
                slug=p["slug"],
                defaults={
                    "name": p["name"],
                    "category": category,
                    "price": Decimal(str(p["price"])),
                    "image": p["image"],
                    "description": p["description"],
                    "tagline": p.get("tagline", ""),
                    "flower_type": p.get("flower_type", cat_slug),
                    "color": p.get("color", ""),
                    "meaning": p.get("meaning", ""),
                    "season": p.get("season", ""),
                    "stem_length": p.get("stem_length", ""),
                    "fragrance": p.get("fragrance", ""),
                    "occasions": p.get("occasions", []),
                    "is_available": True,
                }
            )
            count += 1

        self.stdout.write(self.style.SUCCESS(f"Successfully seeded {count} products! Total in DB: {Product.objects.count()}"))
